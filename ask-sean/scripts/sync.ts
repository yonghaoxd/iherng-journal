/**
 * Read the Buyer Guides and iherng Podcast articles from the live iherng Journal
 * site into knowledge/articles, and record a content hash per article so the
 * enrich step only spends tokens on articles that changed.
 *
 * The article list comes from feed.xml; each article page is parsed by the
 * class names of its "Ask Sean" blocks. If the page layout changes, the sync
 * fails rather than silently dropping content.
 */
import { rm } from "node:fs/promises";
import path from "node:path";
import { parse, type HTMLElement } from "node-html-parser";
import { loadEnv } from "../lib/env";
import {
  ARTICLES_DIR,
  MANIFEST_PATH,
  hashOf,
  listJsonIds,
  readJsonIfExists,
  writeJson,
} from "../lib/knowledge";
import type { Article, Basis, Manifest, Series } from "../lib/types";

const SERIES_BY_CATEGORY: Record<string, Series> = {
  "Buyer Guides": "buyer-guides",
  "iherng Podcast": "iherng-podcast",
};

interface FeedItem {
  link: string;
  category: string;
}

async function fetchText(url: string): Promise<string> {
  const response = await fetch(url, { headers: { "User-Agent": "ask-sean-sync" } });
  if (!response.ok) throw new Error(`GET ${url} failed (${response.status})`);
  return response.text();
}

function decodeXml(text: string): string {
  return text
    .replace(/<!\[CDATA\[([\s\S]*?)\]\]>/g, "$1")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&#39;|&apos;/g, "'")
    .replace(/&amp;/g, "&")
    .trim();
}

/** The feed is generated by the Journal's own build script, so a small regex reader is enough. */
function parseFeed(xml: string): FeedItem[] {
  return [...xml.matchAll(/<item>([\s\S]*?)<\/item>/g)].map(([, item]) => ({
    link: decodeXml(item.match(/<link>([\s\S]*?)<\/link>/)?.[1] ?? ""),
    // The first category is the series; later ones are topic tags.
    category: decodeXml(item.match(/<category>([\s\S]*?)<\/category>/)?.[1] ?? ""),
  }));
}

function text(element: HTMLElement | null | undefined): string {
  return (element?.text ?? "").replace(/\s+/g, " ").trim();
}

function required(root: HTMLElement, selector: string, url: string): string {
  const value = text(root.querySelector(selector));
  if (!value) throw new Error(`${url}: missing "${selector}". Has the article layout changed?`);
  return value;
}

function jsonLd(root: HTMLElement, type: string): Record<string, unknown> {
  for (const script of root.querySelectorAll('script[type="application/ld+json"]')) {
    const data = JSON.parse(script.textContent) as Record<string, unknown>;
    if (data["@type"] === type) return data;
  }
  return {};
}

/** "PT21M9S" → "21:09" */
function formatDuration(iso: string): string {
  const match = iso.match(/PT(?:(\d+)H)?(?:(\d+)M)?(?:(\d+)S)?/);
  if (!match) return "";
  const [hours, minutes, seconds] = match.slice(1).map((part) => Number(part ?? 0));
  const pad = (value: number) => String(value).padStart(2, "0");
  return hours ? `${hours}:${pad(minutes)}:${pad(seconds)}` : `${minutes}:${pad(seconds)}`;
}

function detectBasis(sourceNote: string): Basis {
  if (/captions were unavailable|episode notes only/i.test(sourceNote)) return "episode-notes";
  if (/captions/i.test(sourceNote)) return "captions";
  return "sean-guide";
}

/** A guest answerer (e.g. a lawyer) named on the page; absent when Sean answers. */
function answeredBy(root: HTMLElement): { by?: { name: string; role: string } } {
  const section = root.querySelector(".ask-answer");
  const name = section?.getAttribute("data-answerer-name")?.trim();
  const role = section?.getAttribute("data-answerer-role")?.trim();
  return name ? { by: { name, role: role ?? "" } } : {};
}

function parseArticle(html: string, url: string, series: Series): Article {
  const root = parse(html);
  const page = jsonLd(root, "Article");
  const video = jsonLd(root, "VideoObject");
  const videoUrl = String(video.contentUrl ?? "");
  const videoTitle = String(video.name ?? "");
  const episode = videoTitle.match(/ASKING SEAN #(\d+)/i);
  const sourceNote = required(root, ".sources-note", url);

  return {
    id: url.split("/").filter(Boolean).pop()!,
    series,
    title: String(page.headline ?? "") || required(root, "h1", url),
    excerpt: String(page.description ?? ""),
    date: String(page.datePublished ?? "").slice(0, 10),
    tag: Array.isArray(page.keywords) ? String(page.keywords[0] ?? "") : "",
    question: {
      asker: text(root.querySelector(".ask-asker")),
      context: required(root, ".ask-context", url),
      text: required(root, ".ask-question-text", url),
    },
    answer: {
      ...answeredBy(root),
      quote: required(root, ".ask-quote", url).replace(/^[“"]\s*|\s*[”"]$/g, ""),
      summary: required(root, ".ask-answer-text", url),
    },
    reasons: root.querySelectorAll(".ask-reason").map((reason) => ({
      title: text(reason.querySelector(".ask-reason-title")),
      body: text(reason.querySelector(".ask-reason-body")),
    })),
    actions: root.querySelectorAll(".ask-action-list li").map((item) => text(item)),
    caveat: text(root.querySelector(".ask-caveat p")),
    basis: detectBasis(sourceNote),
    sourceNote,
    askingSeanEpisode: episode ? Number(episode[1]) : null,
    video: {
      id: new URL(videoUrl).searchParams.get("v") ?? "",
      title: videoTitle,
      duration: formatDuration(String(video.duration ?? "")),
      url: videoUrl,
    },
    articleUrl: url,
  };
}

async function main() {
  loadEnv();
  const siteUrl = (process.env.JOURNAL_SITE_URL ?? "https://iherng-journal.pages.dev").replace(/\/+$/, "");
  const items = parseFeed(await fetchText(`${siteUrl}/feed.xml`));

  const previous = (await readJsonIfExists<Manifest>(MANIFEST_PATH))?.articles ?? {};
  const hashes: Manifest["articles"] = {};
  const added: string[] = [];
  const changed: string[] = [];

  for (const item of items.sort((a, b) => a.link.localeCompare(b.link))) {
    const series = SERIES_BY_CATEGORY[item.category];
    if (!series) continue;

    const article = parseArticle(await fetchText(item.link), item.link, series);
    if (article.reasons.length === 0) throw new Error(`${item.link}: no reasons found.`);
    const hash = hashOf(article);
    hashes[article.id] = { hash };
    if (!previous[article.id]) added.push(article.id);
    else if (previous[article.id].hash !== hash) changed.push(article.id);
    await writeJson(path.join(ARTICLES_DIR, `${article.id}.json`), article);
  }

  const removed: string[] = [];
  for (const id of await listJsonIds(ARTICLES_DIR)) {
    if (hashes[id]) continue;
    await rm(path.join(ARTICLES_DIR, `${id}.json`));
    removed.push(id);
  }

  await writeJson(MANIFEST_PATH, { articles: hashes } satisfies Manifest);

  console.log(`Synced ${Object.keys(hashes).length} articles from ${siteUrl}`);
  console.log(`  added: ${added.length ? added.join(", ") : "none"}`);
  console.log(`  changed: ${changed.length ? changed.join(", ") : "none"}`);
  console.log(`  removed: ${removed.length ? removed.join(", ") : "none"}`);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
